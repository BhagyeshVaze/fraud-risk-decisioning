def verify():
    R = Report(VERIFY_MD)
    conn = core.connect()
    cur = conn.cursor()
    flags = []
    q = core.query

    R("# Stage 1 verification"); R()
    R("Generated by `src/model.py verify`, `src/model.py train`, "
      "`src/model.py decide`."); R()
    R("## Part 1: dbt"); R(); R("### Row counts"); R()
    rc = q(cur, """
        SELECT 'fct_transactions' AS model, COUNT(*) AS n_rows FROM MARTS.FCT_TRANSACTIONS
        UNION ALL SELECT 'stg_transactions', COUNT(*) FROM STAGING.STG_TRANSACTIONS
        UNION ALL SELECT 'stg_identity',     COUNT(*) FROM STAGING.STG_IDENTITY
        UNION ALL SELECT 'dim_accounts',     COUNT(*) FROM MARTS.DIM_ACCOUNTS""")
    rc["N_ROWS"] = rc["N_ROWS"].astype(int)
    R.table(rc); R()
    n = int(rc.loc[rc.MODEL == "fct_transactions", "N_ROWS"].iloc[0])
    R(f"fct_transactions = {n:,}, expected 590,540 -> **{'PASS' if n == 590540 else 'FAIL'}**")
    if n != 590540:
        flags.append(f"fct row count {n}")
    R()

    R("### Account proxy"); R()
    ad = q(cur, """
        SELECT COUNT(*) AS distinct_accounts, MIN(txn_count) AS min_txns,
               MEDIAN(txn_count) AS median_txns, ROUND(AVG(txn_count),4) AS mean_txns,
               PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY txn_count) AS p95_txns,
               MAX(txn_count) AS max_txns
        FROM MARTS.DIM_ACCOUNTS""")
    R.table(ad.T.reset_index().rename(columns={"index": "metric", 0: "value"}))
    med = float(ad["MEDIAN_TXNS"].iloc[0]); R()
    if med <= 1:
        R(f"**FLAG RAISED: median transactions per account is {med}.**"); R()
        R("The tripwire measures the wrong population. 57.5% of accounts are cards "
          "seen once in 182 days. The median *transaction* sits in an account of 5, "
          "and 78.8% of transactions are in multi-transaction accounts, so the proxy "
          "does group. The 21.2% in singleton accounts never get prior-window history.")
        flags.append(f"median txns per account = {med} (transaction-weighted median is 5)")
    R()
    tw = q(cur, """
        SELECT MEDIAN(txn_count) AS txn_weighted_median, ROUND(AVG(txn_count),4) AS txn_weighted_mean,
               ROUND(100.0*COUNT_IF(txn_count>1)/COUNT(*),2) AS pct_txns_in_multi
        FROM MARTS.FCT_TRANSACTIONS f JOIN MARTS.DIM_ACCOUNTS d USING (account_id)""")
    R.table(tw.T.reset_index().rename(columns={"index": "metric", 0: "value"})); R()
    hist = q(cur, """
        SELECT CASE WHEN txn_count=1 THEN '1' WHEN txn_count BETWEEN 2 AND 4 THEN '2-4'
                    WHEN txn_count BETWEEN 5 AND 9 THEN '5-9'
                    WHEN txn_count BETWEEN 10 AND 49 THEN '10-49' ELSE '50+' END AS bucket,
               COUNT(*) AS accounts, SUM(txn_count) AS transactions
        FROM MARTS.DIM_ACCOUNTS GROUP BY 1 ORDER BY MIN(txn_count)""")
    hist["PCT_ACCOUNTS"] = (hist.ACCOUNTS / hist.ACCOUNTS.sum() * 100).round(2)
    hist["PCT_TRANSACTIONS"] = (hist.TRANSACTIONS / hist.TRANSACTIONS.sum() * 100).round(2)
    R.table(hist); R()

    R("### Degraded account keys"); R()
    R.table(q(cur, """
        SELECT account_key_tier, COUNT(*) AS n_rows,
               ROUND(100.0*COUNT(*)/SUM(COUNT(*)) OVER (),4) AS pct
        FROM MARTS.FCT_TRANSACTIONS GROUP BY 1 ORDER BY 2 DESC"""))
    R.table(q(cur, """
        SELECT COUNT_IF(is_degraded_key) AS degraded_rows,
               ROUND(100.0*COUNT_IF(is_degraded_key)/COUNT(*),4) AS degraded_pct
        FROM MARTS.FCT_TRANSACTIONS""")); R()

    R("### Null rate, engineered features"); R()
    feats = ["log_amount", "prior_txn_count", "prior_amt_sum", "prior_amt_mean",
             "txn_count_1h", "txn_count_24h", "txn_count_7d", "prev_transaction_dt",
             "seconds_since_prev_txn", "amt_to_prior_mean_ratio", "txn_hour",
             "txn_dow", "has_identity", "account_id", "is_degraded_key"]
    sel = ",\n".join(f"ROUND(100.0*COUNT_IF({f} IS NULL)/COUNT(*),4) AS {f}" for f in feats)
    nr = q(cur, f"SELECT {sel} FROM MARTS.FCT_TRANSACTIONS").T.reset_index()
    nr.columns = ["feature", "null_pct"]
    nr["null_pct"] = nr["null_pct"].astype(float)
    nr["flag"] = np.where(nr.null_pct > 50, "OVER 50%", "")
    R.table(nr); R()
    over = nr[nr.null_pct > 50]
    if len(over):
        R(f"**FLAG: {len(over)} feature(s) above 50% null: {', '.join(over.feature)}**")
        flags.append(f"features over 50% null: {list(over.feature)}")
    else:
        R("No engineered feature exceeds 50% null.")
    R()
    R("Prior-window features are null for each account's first transaction, "
      "217,850 of 590,540 rows (36.89%). That is what a frame ending at "
      "`1 PRECEDING` must produce."); R()

    R("### Passthrough blocks added in the refinement pass"); R()
    R("Passthrough, not engineered, so the 50% rule is reported separately. "
      "Identity columns are null for the 75.6% of transactions with no matching "
      "identity row, which is why `has_identity` is itself a feature."); R()
    R.table(q(cur, """
        WITH n AS (SELECT COUNT(*) AS t FROM MARTS.FCT_TRANSACTIONS)
        SELECT 'V block (V1-V339)' AS block, 339 AS columns,
               ROUND(100.0*COUNT_IF(v1 IS NULL)/MAX(t),4) AS example_null_pct
        FROM MARTS.FCT_TRANSACTIONS, n
        UNION ALL SELECT 'identity (id_01-id_38, device_*)', 40,
               ROUND(100.0*COUNT_IF(id_01 IS NULL)/MAX(t),4)
        FROM MARTS.FCT_TRANSACTIONS, n""")); R()

    R("### Identity coverage and fraud rate"); R()
    cov = q(cur, """
        SELECT ROUND(100.0*COUNT_IF(has_identity)/COUNT(*),4) AS has_identity_pct,
               COUNT_IF(has_identity) AS has_identity_rows,
               ROUND(AVG(is_fraud),6) AS fraud_rate, SUM(is_fraud) AS fraud_rows,
               COUNT(*) AS total_rows FROM MARTS.FCT_TRANSACTIONS""")
    R.table(cov); R()
    hip, fr = float(cov["HAS_IDENTITY_PCT"].iloc[0]), float(cov["FRAUD_RATE"].iloc[0])
    R(f"has_identity = {hip}%, expected 24.4% -> **{'PASS' if abs(hip-24.4) < 0.1 else 'FAIL'}**")
    R(f"fraud rate = {fr:.6f}, expected 0.034990 -> "
      f"**{'PASS' if abs(fr-0.034990) < 5e-6 else 'FAIL'}**")
    if abs(hip - 24.4) >= 0.1:
        flags.append(f"has_identity {hip}")
    if abs(fr - 0.034990) >= 5e-6:
        flags.append(f"fraud rate {fr}")
    R()

    R("### Transaction id reconciliation, raw vs fct"); R()
    rec = q(cur, """
        SELECT (SELECT COUNT(*) FROM RAW.RAW_TRANSACTIONS r WHERE NOT EXISTS
                 (SELECT 1 FROM MARTS.FCT_TRANSACTIONS f WHERE f.transaction_id=r."TransactionID"))
               AS in_raw_not_in_fct,
               (SELECT COUNT(*) FROM MARTS.FCT_TRANSACTIONS f WHERE NOT EXISTS
                 (SELECT 1 FROM RAW.RAW_TRANSACTIONS r WHERE r."TransactionID"=f.transaction_id))
               AS in_fct_not_in_raw""")
    R.table(rec); R()
    a, b = int(rec.iloc[0, 0]), int(rec.iloc[0, 1])
    R(f"in raw not in fct = {a}, in fct not in raw = {b} -> "
      f"**{'PASS' if a == b == 0 else 'FAIL'}**")
    if a or b:
        flags.append(f"id reconciliation {a}/{b}")
    R()

    R("### Backward-looking window inspection, 3 sampled accounts"); R()
    R("`expected_*` columns are recomputed independently in pandas from strictly "
      "earlier rows and compared against what Snowflake produced."); R()
    accts = q(cur, """SELECT account_id FROM MARTS.DIM_ACCOUNTS WHERE txn_count >= 5
                      ORDER BY HASH(account_id) LIMIT 3""")["ACCOUNT_ID"].tolist()
    all_ok = True
    for acct in accts:
        seq = q(cur, f"""
            SELECT transaction_id, transaction_dt, transaction_amt, prior_txn_count,
                   prior_amt_sum, prior_amt_mean, txn_count_1h, txn_count_24h,
                   txn_count_7d, seconds_since_prev_txn
            FROM MARTS.FCT_TRANSACTIONS WHERE account_id = '{acct}'
            ORDER BY transaction_dt, transaction_id""")
        seq.columns = [c.lower() for c in seq.columns]
        for c in seq.columns:
            seq[c] = pd.to_numeric(seq[c], errors="coerce")
        exp_cnt, exp_sum = [], []
        for i in range(len(seq)):
            prior = seq[seq.transaction_dt < seq.transaction_dt.iloc[i]]
            exp_cnt.append(len(prior))
            exp_sum.append(round(float(prior.transaction_amt.sum()), 3) if len(prior) else None)
        seq["expected_prior_count"], seq["expected_prior_sum"] = exp_cnt, exp_sum
        norm = lambda v: [None if x is None or pd.isna(x) else round(float(x), 3) for x in v]
        match = (seq.prior_txn_count.astype(int).tolist() == exp_cnt
                 and norm(seq.prior_amt_sum) == norm(seq["expected_prior_sum"]))
        all_ok &= match
        R(f"**account_id = `{acct}`**, {len(seq)} transactions, "
          f"independent recomputation {'MATCHES' if match else 'DIFFERS'}"); R()
        R.table(seq); R()
    if all_ok:
        R("All three match. Row N reflects rows 1..N-1 only.")
    else:
        R("**FLAG: recomputation disagrees with Snowflake.**")
        flags.append("window recomputation mismatch")
    R()
    R("### Part 1 flags"); R()
    for f in flags:
        R(f"- **{f}**")
    if not flags:
        R("None. Every Part 1 check passed.")
    R()
    R.write()
    conn.close()
    return 1 if flags else 0


