def fetch():
    if core.FCT.exists():
        print(f"reading cached {core.FCT}")
        return pd.read_parquet(core.FCT)
    conn = core.connect()
    cur = conn.cursor()
    print("pulling FCT_TRANSACTIONS...")
    cur.execute("SELECT * FROM MARTS.FCT_TRANSACTIONS")

    # 443 columns x 590k rows does not fit comfortably in 8 GB as float64, so
    # stream arrow batches to parquet, narrowing types on the way.
    import pyarrow as pa
    import pyarrow.parquet as pq

    def shrink(t):
        if pa.types.is_float64(t):
            return pa.float32()
        if pa.types.is_decimal(t):
            return pa.int64() if t.scale == 0 else pa.float64()
        return t

    core.DATA.mkdir(parents=True, exist_ok=True)
    writer, n = None, 0
    for batch in cur.fetch_arrow_batches():
        tbl = batch if isinstance(batch, pa.Table) else pa.Table.from_batches([batch])
        schema = pa.schema([pa.field(f.name.lower(), shrink(f.type)) for f in tbl.schema])
        tbl = tbl.rename_columns([c.lower() for c in tbl.schema.names]).cast(schema)
        if writer is None:
            writer = pq.ParquetWriter(core.FCT, schema, compression="snappy")
        writer.write_table(tbl)
        n += tbl.num_rows
    writer.close()
    conn.close()
    print(f"cached {n:,} rows to {core.FCT}")
    return pd.read_parquet(core.FCT)


def reliability_plot(y, p_raw, p_cal, path):
    fig, ax = plt.subplots(figsize=(7.2, 5.6), facecolor=SURFACE)
    ax.plot([0, 1], [0, 1], color=GRIDC, lw=2, ls="--", zorder=1)
    ax.annotate("perfect calibration", xy=(0.25, 0.25), xytext=(-10, 8),
                textcoords="offset points", ha="right", va="bottom",
                color=INK_2, fontsize=9)
    for p, color, label in ((p_raw, C_BEFORE, "before calibration"),
                            (p_cal, C_AFTER, "after isotonic")):
        ft, mp = calibration_curve(y, p, n_bins=10, strategy="quantile")
        ax.plot(mp, ft, color=color, lw=2, marker="o", ms=8, label=label,
                markeredgecolor=SURFACE, markeredgewidth=2, zorder=3)
    lo = min(p_raw.min(), p_cal.min())
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlim(max(lo, 1e-4), 1.0); ax.set_ylim(max(lo, 1e-4), 1.0)
    style(ax, "Reliability on the test split (log-log, quantile bins)",
          "mean predicted probability", "observed fraud rate")
    leg = ax.legend(frameon=False, fontsize=9.5, loc="upper left")
    for t in leg.get_texts():
        t.set_color(INK_2)
    fig.tight_layout(); fig.savefig(path, dpi=170, facecolor=SURFACE)
    print(f"wrote {path}")


def train():
    R = Report(VERIFY_MD)
    MODELS.mkdir(exist_ok=True); REPORTS.mkdir(exist_ok=True)
    df = fetch()
    df.columns = [c.lower() for c in df.columns]

    R(); R("## Part 2: the model"); R(); R("### Time splits"); R()
    R("Four disjoint windows, so early stopping and calibration never share data."); R()
    tr = df[df.txn_day < core.TRAIN_MAX_DAY]
    es = df[(df.txn_day >= core.TRAIN_MAX_DAY) & (df.txn_day < core.ES_MAX_DAY)]
    ca = df[(df.txn_day >= core.ES_MAX_DAY) & (df.txn_day < core.CAL_MAX_DAY)]
    te = df[df.txn_day >= core.CAL_MAX_DAY]
    rows = []
    for name, part, rng in (("train", tr, f"txn_day < {core.TRAIN_MAX_DAY}"),
                            ("early stopping", es, f"{core.TRAIN_MAX_DAY} <= txn_day < {core.ES_MAX_DAY}"),
                            ("calibration", ca, f"{core.ES_MAX_DAY} <= txn_day < {core.CAL_MAX_DAY}"),
                            ("test", te, f"txn_day >= {core.CAL_MAX_DAY}")):
        f = part.is_fraud.mean()
        rows.append({"split": name, "day_range": rng, "rows": len(part),
                     "fraud": int(part.is_fraud.sum()), "fraud_rate": round(f, 6),
                     "dev_vs_0.0350_pct": round((f - 0.034990) / 0.034990 * 100, 2)})
    sp = pd.DataFrame(rows)
    R.table(sp); R()
    drift = sp[sp["dev_vs_0.0350_pct"].abs() > 30]
    R(f"**FLAG: {len(drift)} split(s) deviate more than 30% from 0.0350.**" if len(drift)
      else "No split deviates more than 30% from the 0.0350 base rate.")
    R(); R(f"Total across splits: {len(tr)+len(es)+len(ca)+len(te):,} of {len(df):,} rows."); R()

    feats = [c for c in df.columns if c not in EXCLUDE]
    X, cats = core.encode(df[feats])
    sel_path = MODELS / "selected_features.json"
    if sel_path.exists():
        sel = json.loads(sel_path.read_text())
        feats = [f for f in sel["features"] if f in X.columns]
        cats = [c for c in cats if c in feats]
        X = X[feats]
        print(f"using pruned feature set: {sel['variant']}, {len(feats)} features")
    y = df.is_fraud.astype("int8")
    Xtr, Xes, Xca, Xte = X.loc[tr.index], X.loc[es.index], X.loc[ca.index], X.loc[te.index]
    ytr, yes_, yca, yte = y.loc[tr.index], y.loc[es.index], y.loc[ca.index], y.loc[te.index]
    del X

    R("### Features"); R()
    R(f"Features used: **{len(feats)}** ({len(cats)} categorical, "
      f"{len(feats)-len(cats)} numeric)."); R()
    leaked = [c for c in ("transaction_id", "account_id", "txn_day", "transaction_dt")
              if c in feats]
    R(f"Excluded by design: {sorted(EXCLUDE)}"); R()
    R(f"Identifier/time columns in the feature list: {leaked or 'none'} -> "
      f"**{'FAIL' if leaked else 'PASS'}**"); R()

    clf = lgb.LGBMClassifier(**core.LGB_PARAMS)
    clf.fit(Xtr, ytr, eval_set=[(Xes, yes_)], eval_metric="average_precision",
            categorical_feature=cats,
            callbacks=[lgb.early_stopping(100, verbose=False), lgb.log_evaluation(0)])
    R(f"Best iteration on the early stopping split (days {core.TRAIN_MAX_DAY}-"
      f"{core.ES_MAX_DAY-1}): **{clf.best_iteration_}** of 3000, patience 100."); R()

    # Fitted on days 130-149, which the model saw during neither training nor
    # early stopping.
    cal = CalibratedClassifierCV(FrozenEstimator(clf), method="isotonic")
    cal.fit(Xca, yca)
    p_tr = clf.predict_proba(Xtr)[:, 1]
    p_raw, p_cal = clf.predict_proba(Xte)[:, 1], cal.predict_proba(Xte)[:, 1]

    m = {"train_pr_auc": average_precision_score(ytr, p_tr),
         "test_pr_auc_raw": average_precision_score(yte, p_raw),
         "test_pr_auc_cal": average_precision_score(yte, p_cal),
         "test_roc_auc_raw": roc_auc_score(yte, p_raw),
         "test_roc_auc_cal": roc_auc_score(yte, p_cal),
         "test_brier_raw": brier_score_loss(yte, p_raw),
         "test_brier_cal": brier_score_loss(yte, p_cal)}
    R("### Test metrics"); R(); R.block(pd.Series(m).round(6).to_string()); R()
    gap = m["train_pr_auc"] - m["test_pr_auc_raw"]
    R(f"Train PR-AUC {m['train_pr_auc']:.4f} vs test {m['test_pr_auc_raw']:.4f}, "
      f"gap {gap:+.4f}.")
    R(f"Test PR-AUC {m['test_pr_auc_raw']:.4f} is "
      f"{'above' if m['test_pr_auc_raw'] > 0.85 else 'below'} the 0.85 suspicion threshold.")
    if gap > 0.15:
        R(f"**FLAG: train/test PR-AUC gap {gap:.4f} suggests overfitting.** "
          "Attacking it directly made the model worse; see "
          "reports/improvements_summary.md.")
    R()
    delta = m["test_brier_raw"] - m["test_brier_cal"]
    R(f"Brier {'improved' if delta > 0 else 'degraded'} under calibration: "
      f"{m['test_brier_raw']:.6f} -> {m['test_brier_cal']:.6f} "
      f"({delta/m['test_brier_raw']*100:+.2f}%).")
    if delta <= 0:
        R(); R("**FLAG: isotonic did not improve Brier on test.** The remaining "
               "cause is drift between the calibration and test periods.")
    R()

    R("### Full 437 vs this run, side by side"); R()
    cmp = pd.DataFrame([
        {"metric": "features", "stage_1": BASELINE["n_features"], "this_run": len(feats)},
        {"metric": "train PR-AUC", "stage_1": BASELINE["train_pr_auc"], "this_run": m["train_pr_auc"]},
        {"metric": "test PR-AUC (raw)", "stage_1": BASELINE["test_pr_auc_raw"], "this_run": m["test_pr_auc_raw"]},
        {"metric": "test PR-AUC (cal)", "stage_1": BASELINE["test_pr_auc_cal"], "this_run": m["test_pr_auc_cal"]},
        {"metric": "test ROC-AUC (raw)", "stage_1": BASELINE["test_roc_auc_raw"], "this_run": m["test_roc_auc_raw"]},
        {"metric": "test Brier (raw)", "stage_1": BASELINE["test_brier_raw"], "this_run": m["test_brier_raw"]},
        {"metric": "test Brier (cal)", "stage_1": BASELINE["test_brier_cal"], "this_run": m["test_brier_cal"]},
        {"metric": "train/test gap", "stage_1": BASELINE["train_pr_auc"] - BASELINE["test_pr_auc_raw"], "this_run": gap}])
    cmp["delta"] = cmp.this_run - cmp.stage_1
    R.table(cmp.round(6)); R()
    R("Both runs use identical splits, so this comparison is clean."); R()

    imp = pd.DataFrame({"feature": feats, "gain": clf.booster_.feature_importance("gain")})
    imp["pct_of_total_gain"] = imp.gain / imp.gain.sum() * 100
    imp = imp.sort_values("gain", ascending=False).reset_index(drop=True)
    R("### Top 25 features by gain"); R(); R.table(imp.head(25).round(4)); R()
    top = imp.iloc[0]
    R(f"{'**FLAG: ' if top.pct_of_total_gain > 30 else 'No single feature dominates: '}"
      f"`{top.feature}` carries {top.pct_of_total_gain:.2f}% of total gain"
      f"{', above the 30% dominance threshold.**' if top.pct_of_total_gain > 30 else ', below the 30% threshold.'}")
    R()

    R("### Predicted probability distribution on test"); R()
    dist = pd.DataFrame({
        "statistic": ["min", "p25", "median", "p75", "p95", "max", "mean"],
        "raw": [p_raw.min(), *np.quantile(p_raw, [.25, .5, .75, .95]), p_raw.max(), p_raw.mean()],
        "calibrated": [p_cal.min(), *np.quantile(p_cal, [.25, .5, .75, .95]), p_cal.max(), p_cal.mean()]})
    R.table(dist.round(6)); R()
    R(f"Actual test fraud rate: {yte.mean():.6f}. Mean calibrated probability: "
      f"{p_cal.mean():.6f} (difference {p_cal.mean()-yte.mean():+.6f})."); R()

    R("### Decile calibration, predicted vs actual"); R()
    for label, p in (("before calibration", p_raw), ("after isotonic", p_cal)):
        d = pd.DataFrame({"p": p, "y": yte.values})
        d["decile"] = pd.qcut(d.p.rank(method="first"), 10, labels=range(1, 11))
        g = d.groupby("decile", observed=True).agg(
            n=("y", "size"), predicted=("p", "mean"), actual=("y", "mean")).reset_index()
        g["abs_diff"] = (g.predicted - g.actual).abs()
        R(f"**{label}**"); R(); R.table(g.round(6)); R()

    reliability_plot(yte.values, p_raw, p_cal, REPORTS / "calibration_curve.png")
    R("Reliability curve: `reports/calibration_curve.png`."); R()

    joblib.dump(clf, MODELS / "lgbm_fraud_model.joblib")
    joblib.dump(cal, MODELS / "isotonic_calibrator.joblib")
    clf.booster_.save_model(str(MODELS / "lgbm_fraud_model.txt"))
    (MODELS / "model_metadata.json").write_text(json.dumps(
        {"best_iteration": int(clf.best_iteration_), "n_features": len(feats),
         "categorical_features": cats, "features": feats,
         "splits": {"train_max_day": core.TRAIN_MAX_DAY, "es_max_day": core.ES_MAX_DAY,
                    "cal_max_day": core.CAL_MAX_DAY},
         "metrics": {k: float(v) for k, v in m.items()}, "seed": core.SEED}, indent=2))
    R("Saved to `models/`: lgbm_fraud_model.joblib, isotonic_calibrator.joblib, "
      "lgbm_fraud_model.txt, model_metadata.json."); R()

    np.save(REPORTS / "_test_probs.npy", p_cal)
    np.save(REPORTS / "_test_probs_raw.npy", p_raw)
